char *language_container[LANGUAGE_CONTAINER_SIZE];

void freeLanguageContainer() {
  int i;
  for (i = 0; i < LANGUAGE_CONTAINER_SIZE; i++) {
    if (language_container[i]) {
      free(language_container[i]);
      language_container[i] = NULL;
    }
  }
}

